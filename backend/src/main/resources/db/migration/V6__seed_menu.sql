insert into product_variants (product_id, name, size, sort_order)
select p.id, sp.variant, sp.size, sp.sort_order
from seed_prices sp
join categories c on c.business_id = 1 and c.name = sp.category
join products p on p.business_id = 1 and p.category_id = c.id and p.name = sp.name
  and coalesce(p.subcategory,'') = coalesce(sp.subcategory,'');

